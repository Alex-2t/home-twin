// Builds the editor into a single file dist/index.html. node build.ts [--serve] [--demo=<module>]
// The demo apartment is embedded into src/gen/ (in .gitignore): demo/own.ts is the owner's apartment, local only (.gitignore), and it
// is used if the file exists; otherwise demo/typical.ts, the typical three-room apartment from the repository. --demo=<name> takes
// demo/<name>.ts instead (--demo=typical, --demo=homes/studio). The ten typical homes (demo/homes.ts, D-030) go in too: the start
// screen's examples (D-062).
// Each generated module gets a .d.ts beside it, in the shared types, so the typed code can import it (D-087).
import fs from 'node:fs';
import crypto from 'node:crypto';
import * as esbuild from 'esbuild';
import {execFile} from 'node:child_process';
import type {DemoHomeModule} from './demo/kit.ts';
import type {ExampleHome} from './src/core/types.ts';

fs.mkdirSync('src/gen', {recursive: true});
fs.mkdirSync('dist', {recursive: true});

// The types of the generated modules: src/gen/<name>.gen.d.ts beside src/gen/<name>.gen.js
const GEN_TYPES_HEAD = '// Generated by build.ts: the types of the module beside it.\n';
const writeGenTypes = (name: string, declarations: string): void =>
  fs.writeFileSync(`src/gen/${name}.gen.d.ts`, GEN_TYPES_HEAD + declarations);

// Kenney models (CC0)
const models = Object.fromEntries(
  fs
    .readdirSync('assets/kenney')
    .filter(f => f.endsWith('.glb'))
    .map(f => [f.slice(0, -4), fs.readFileSync('assets/kenney/' + f).toString('base64')]),
);
fs.writeFileSync('src/gen/models.gen.js', 'export const MODELS=' + JSON.stringify(models) + ';\n');
writeGenTypes(
  'models',
  '/** Kenney models (CC0): the model name → its .glb file in base64. */\nexport declare const MODELS: Record<string, string>;\n',
);

// Demo (D-033 sensors, D-048 devices, D-049 favorites, “Statistics”, weather) — in the apartment module, shared parts in demo/kit.ts
const demoArg = process.argv.find(a => a.startsWith('--demo='));
const demoName = demoArg?.slice(7) || (fs.existsSync('demo/own.ts') ? 'own' : 'typical');
async function genDemo(): Promise<void> {
  // one of the demo modules (demo/kit.ts says what each gives)
  const demoModule: DemoHomeModule = await import(`./demo/${demoName}.ts`);
  const {HA, DEMO, DEMO_UNDERLAY} = await demoModule.default();
  fs.writeFileSync(
    'src/gen/demo.gen.js',
    `export const DEMO_NAME=${JSON.stringify(demoName)};\nexport const HA=${JSON.stringify(HA)};\nexport const DEMO=${JSON.stringify(DEMO)};\nexport const DEMO_UNDERLAY=${JSON.stringify(DEMO_UNDERLAY)};\n`,
  );
  writeGenTypes(
    'demo',
    "import type {DemoHome} from '../core/types.ts';\n" +
      "/** The build's demo home: 'own', 'typical' or the module --demo= names. */\n" +
      'export declare const DEMO_NAME: string;\n' +
      "export declare const HA: DemoHome['HA'];\n" +
      "export declare const DEMO: DemoHome['DEMO'];\n" +
      "export declare const DEMO_UNDERLAY: DemoHome['DEMO_UNDERLAY'];\n",
  );
  console.log('demo:', demoName);
  const {HOMES} = await import('./demo/homes.ts');
  // a home whose module fails to load (being written) is left out with a warning, the build goes on
  const examples: ExampleHome[] = (
    await Promise.all(
      HOMES.map(async (h): Promise<ExampleHome | null> => {
        try {
          const d = await h.load();
          return {id: h.id, HA: d.HA, DEMO: d.DEMO};
        } catch (e) {
          // a module that cannot be loaded or run throws an Error
          console.warn('example left out:', h.id, '—', (e as Error).message.split('\n')[0]);
          return null;
        }
      }),
    )
  ).filter(home => home !== null);
  fs.writeFileSync('src/gen/examples.gen.js', 'export const EXAMPLES=' + JSON.stringify(examples) + ';\n');
  writeGenTypes(
    'examples',
    "import type {ExampleHome} from '../core/types.ts';\n" +
      "/** The start screen's examples (D-062): the typical homes. */\n" +
      'export declare const EXAMPLES: ExampleHome[];\n',
  );
}
await genDemo();
// --gen-demo: only the demo files (the dev server runs it in a fresh process when demo/ changes: imported modules are cached)
if (process.argv.includes('--gen-demo')) process.exit(0);

// styles and the shell are read on every build: with --serve they can be edited without a restart (styles used to be read once at
// startup, and a rebuild after a code edit overwrote the new styles with the old ones)
const html = (js: string): string =>
  fs
    .readFileSync('src/shell.html', 'utf8')
    .replace('/*STYLES*/', () => fs.readFileSync('src/styles.css', 'utf8'))
    .replace('/*BUNDLE*/', () => js.replace(/<\/script/g, '<\\/script'));
// .css imported from JS as text: the apartment card styles (src/look/card.css) go into its Shadow DOM
const opts = {
  entryPoints: ['src/main.ts'],
  outfile: 'dist/bundle.js',
  bundle: true,
  format: 'esm',
  minify: true,
  write: false,
  target: 'es2022',
  logLevel: 'warning',
  loader: {'.css': 'text'},
  charset: 'utf8',
} satisfies esbuild.BuildOptions;
const write = (result: esbuild.BuildResult): void => {
  // opts has write: false, so esbuild hands the bundle back instead of writing it
  const out = html(result.outputFiles![0].text);
  fs.writeFileSync('dist/index.html', out);
  console.log('dist/index.html', (out.length / 1024).toFixed(0), 'KB');
};
// The Home Assistant panel (the custom_components/home_twin integration): a single module frontend/panel.js with the styles and
// shell inside (src/gen/shell.gen.js), without the demo apartment or personal data. Non-ASCII text (e.g. Cyrillic) stays as is (charset utf8):
// module scripts are always UTF-8, and \uXXXX escapes bloated the bundle by a third.
const PANEL = '../custom_components/home_twin/frontend/panel.js';
function shellGen(): void {
  const src = fs.readFileSync('src/shell.html', 'utf8');
  // shell.html always has the body with the module script at its end
  const match = src.match(/<body([^>]*)>([\s\S]*?)<script type="module">/)!;
  const body = [...match[1].matchAll(/([\w-]+)="([^"]*)"/g)].map((x): [string, string] => [x[1], x[2]]);
  // inline scripts of the page (the example cover) do not run in the panel: left out
  fs.writeFileSync(
    'src/gen/shell.gen.js',
    `export const SHELL=${JSON.stringify(match[2].replace(/<script>[\s\S]*?<\/script>\n?/g, ''))};\nexport const BODY=${JSON.stringify(body)};\nexport const STYLES=${JSON.stringify(fs.readFileSync('src/styles.css', 'utf8'))};\n`,
  );
  writeGenTypes(
    'shell',
    '/** The editor shell for the HA panel (shell.html): its markup, the attributes of its body, its styles. */\n' +
      'export declare const SHELL: string;\n' +
      'export declare const BODY: Array<[string, string]>;\n' +
      'export declare const STYLES: string;\n',
  );
}
shellGen();

// The words of the “Home Twin was updated · Reload” notice in every language, for the card's small loader (card.ts), which cannot
// carry the dictionaries. The panel says the same through t(), so the translation check covers these words too.
const UPDATE_NOTICE_KEYS = {text: 'Home Twin was updated', reload: 'Reload'};
function updateNoticeGen(): void {
  const notice: Record<string, {text: string; reload: string}> = {en: UPDATE_NOTICE_KEYS};
  for (const file of fs.readdirSync('src/i18n')) {
    if (!/^[a-z]{2}\.json$/.test(file)) continue;
    // a language file: the English text → its translation
    const dictionary = JSON.parse(fs.readFileSync('src/i18n/' + file, 'utf8')) as Record<string, string>;
    notice[file.slice(0, 2)] = {
      text: dictionary[UPDATE_NOTICE_KEYS.text] || UPDATE_NOTICE_KEYS.text,
      reload: dictionary[UPDATE_NOTICE_KEYS.reload] || UPDATE_NOTICE_KEYS.reload,
    };
  }
  fs.writeFileSync('src/gen/update-notice.gen.js', `export const UPDATE_NOTICE=${JSON.stringify(notice)};\n`);
  writeGenTypes(
    'update-notice',
    '/** The update notice in every language: language → its text and the reload button. */\n' +
      'export declare const UPDATE_NOTICE: Record<string, {text: string; reload: string}>;\n',
  );
}
updateNoticeGen();

fs.mkdirSync('../custom_components/home_twin/frontend', {recursive: true});
const panelOpts = {
  ...opts,
  entryPoints: ['src/ha-panel.ts'],
  outfile: PANEL,
  write: true,
} satisfies esbuild.BuildOptions;
const panelDone = (): void => console.log('panel.js', (fs.statSync(PANEL).size / 1024).toFixed(0), 'KB');
// The dashboard card (D-059): card.js — a small file HA loads on every page; card-app.js — the 3D and the home panel,
// loaded only where a card is shown
const FRONT = '../custom_components/home_twin/frontend/';
// --serve rebuilds the files one at a time: build.json is written again after each
const watching = process.argv.includes('--serve');

// build.json beside the files: every file's sha256 and the build id made from them. The integration serves each build at its own
// address and takes a new one up only once the files on disk match this list, so an update half done is never served (serve.py,
// D-097). The id is made the way serve.py makes it: the sha256 of the "name:sha256" lines in name order, its first 12 characters.
const FRONTEND_FILE = /^[a-z0-9][a-z0-9-]*\.js$/;
const BUILD_ID_LENGTH = 12;
const sha256 = (data: string | Buffer): string => crypto.createHash('sha256').update(data).digest('hex');
function writeBuildManifest(): void {
  const names = fs
    .readdirSync(FRONT)
    .filter(name => FRONTEND_FILE.test(name))
    .sort();
  const files: Record<string, string> = {};
  for (const name of names) files[name] = sha256(fs.readFileSync(FRONT + name));
  const lines = names.map(name => `${name}:${files[name]}\n`).join('');
  const build = sha256(lines).slice(0, BUILD_ID_LENGTH);
  fs.writeFileSync(FRONT + 'build.json', JSON.stringify({build, files}, null, 1) + '\n');
  console.log('build.json', build);
}
const cardOpts = ['card', 'card-app'].map((n): esbuild.BuildOptions => ({
  ...opts,
  entryPoints: [`src/${n}.ts`],
  outfile: FRONT + n + '.js',
  write: true,
  plugins: [
    {
      name: 'done',
      setup(b) {
        b.onEnd(r => {
          if (r.errors.length) return;
          console.log(n + '.js', (fs.statSync(FRONT + n + '.js').size / 1024).toFixed(0), 'KB');
          if (watching) writeBuildManifest();
        });
      },
    },
  ],
}));
if (watching) {
  const ctx = await esbuild.context({
    ...opts,
    plugins: [
      {
        name: 'html',
        setup(b) {
          b.onEnd(r => {
            if (!r.errors.length) write(r);
          });
        },
      },
    ],
  });
  await ctx.watch();
  const {port} = await ctx.serve({servedir: 'dist', port: 8766});
  console.log(`http://localhost:${port}/`);
  // styles and the shell are not in esbuild's module graph — watch them ourselves
  const pctx = await esbuild.context({
    ...panelOpts,
    plugins: [
      {
        name: 'done',
        setup(b) {
          b.onEnd(r => {
            if (r.errors.length) return;
            panelDone();
            writeBuildManifest();
          });
        },
      },
    ],
  });
  await pctx.watch();
  for (const o of cardOpts) await (await esbuild.context(o)).watch();
  // watch the folder, not the files: editors save by replacing the file, and a watch on the old file then goes silent on macOS
  let t: NodeJS.Timeout | number = 0;
  fs.watch('src', (_e, f) => {
    if (!['styles.css', 'shell.html'].includes(String(f))) return;
    clearTimeout(t);
    t = setTimeout(() => {
      shellGen();
      ctx.rebuild().catch(() => {});
    }, 80);
  });
  // the demo homes (demo/): regenerated in a child process, esbuild then sees src/gen/ change and rebuilds
  let dt: NodeJS.Timeout | number = 0;
  fs.watch('demo', {recursive: true}, (_e, f) => {
    if (!String(f).endsWith('.ts')) return;
    clearTimeout(dt);
    dt = setTimeout(() => {
      execFile(process.execPath, ['build.ts', '--gen-demo', ...(demoArg ? [demoArg] : [])], (e, out, err) => {
        process.stdout.write(out);
        process.stderr.write(err);
      });
    }, 250);
  });
} else {
  write(await esbuild.build(opts));
  await esbuild.build(panelOpts);
  panelDone();
  for (const o of cardOpts) await esbuild.build(o);
  writeBuildManifest();
}
